
#!/usr/bin/env python3

import json
import os
import pickle
import stat
import tempfile
from pathlib import Path


CONFIG = Path.home() / ".config" / "ai_file_cleaner"

OLD_FILE = CONFIG / "qtable.pkl"
NEW_FILE = CONFIG / "qtable.json"

Q_SHAPE = (7, 5, 5, 7, 2)
COUNTS_SHAPE = (7, 5, 5, 7)


def valid_tree(data, shape, integer=False):

    if not isinstance(data, list):
        return False

    if len(data) != shape[0]:
        return False

    if len(shape) == 1:

        for value in data:

            if integer:

                if type(value) is not int or value < 0:
                    return False

            else:

                if isinstance(value, bool):
                    return False

                if not isinstance(value, (int, float)):
                    return False

                if not (-1000000 < float(value) < 1000000):
                    return False

        return True

    return all(
        valid_tree(item, shape[1:], integer)
        for item in data
    )


def main():

    if os.geteuid() == 0:
        raise SystemExit(
            "Run this migration as your normal user, NOT as root."
        )

    if not OLD_FILE.exists():
        raise SystemExit("No old qtable.pkl found.")

    if NEW_FILE.exists():
        raise SystemExit(
            "qtable.json already exists. Nothing was changed."
        )

    st = OLD_FILE.stat()

    if st.st_uid != os.getuid():
        raise SystemExit(
            "The old Q-table is not owned by the current user."
        )

    if st.st_mode & (stat.S_IWGRP | stat.S_IWOTH):
        raise SystemExit(
            "The old Q-table is writable by other users. "
            "Migration aborted."
        )

    print("Reading the old Q-table...")
    print("Only migrate a pickle generated by your trusted old installation.")

    try:
        with OLD_FILE.open("rb") as f:
            data = pickle.load(f)

    except Exception as exc:
        raise SystemExit(f"Could not read old Q-table: {exc}")

    q = data["Q"]
    counts = data["counts"]

    if hasattr(q, "tolist"):
        q = q.tolist()

    if hasattr(counts, "tolist"):
        counts = counts.tolist()

    if not valid_tree(q, Q_SHAPE):
        raise SystemExit("Invalid Q-table shape or values.")

    if not valid_tree(counts, COUNTS_SHAPE, integer=True):
        raise SystemExit("Invalid counts structure.")

    conf_stats = {
        str(float(bucket)): pair
        for bucket, pair in data.get("conf_stats", {}).items()
    }

    conf_stats_ctx = []

    for key, pair in data.get("conf_stats_ctx", {}).items():

        bucket, ext, loc = key

        conf_stats_ctx.append({
            "bucket": float(bucket),
            "ext": int(ext),
            "loc": int(loc),
            "shown": int(pair[0]),
            "accepted": int(pair[1]),
        })

    payload = {
        "version": 1,
        "Q": q,
        "counts": counts,
        "conf_stats": conf_stats,
        "conf_stats_ctx": conf_stats_ctx,
        "conf_history": data.get("conf_history", []),
    }

    CONFIG.mkdir(parents=True, exist_ok=True)

    fd, temp_path = tempfile.mkstemp(
        dir=CONFIG,
        prefix=".qtable-",
        suffix=".tmp",
    )

    try:

        with os.fdopen(fd, "w", encoding="utf-8") as f:

            json.dump(
                payload,
                f,
                separators=(",", ":"),
            )

            f.flush()
            os.fsync(f.fileno())

        os.chmod(temp_path, 0o600)
        os.replace(temp_path, NEW_FILE)

    except Exception:
        if os.path.exists(temp_path):
            os.unlink(temp_path)
        raise

    print("Migration successful!")
    print(f"New Q-table: {NEW_FILE}")
    print("Original qtable.pkl was preserved.")


if __name__ == "__main__":
    main()
